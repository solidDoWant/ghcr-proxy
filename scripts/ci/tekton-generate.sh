#!/usr/bin/env bash
# Writes the CI PipelineRuns .tekton/pull-request.yaml and .tekton/push.yaml
# from scripts/ci/tekton-pipelinerun.yaml.tmpl (`make generate`), so the two
# differ only where the template says.
set -euo pipefail
cd "$(git rev-parse --show-toplevel)"

template=scripts/ci/tekton-pipelinerun.yaml.tmpl

# render NAME EVENT CEL CANCEL: writes .tekton/NAME.yaml, without the
# template's own header comment, and with the pull-request-only lines only
# for pull requests.
render() {
	{
		echo "# Generated by scripts/ci/tekton-generate.sh from $template. Do not edit."
		awk -v name="$1" -v event="$2" -v cel="$3" -v cancel="$4" '
			function replace(text, from, to,   out, at) {
				out = ""
				while ((at = index(text, from)) > 0) {
					out = out substr(text, 1, at - 1) to
					text = substr(text, at + length(from))
				}
				return out text
			}
			/^apiVersion:/ { started = 1 }
			!started { next }
			/^#@pull_request \{$/ { inside = 1; next }
			/^#@pull_request \}$/ { inside = 0; next }
			inside && event != "pull_request" { next }
			{
				line = replace($0, "@NAME@", name)
				line = replace(line, "@EVENT@", event)
				line = replace(line, "@CEL@", cel)
				print replace(line, "@CANCEL@", cancel)
			}
		' "$template"
	} >".tekton/$1.yaml.tmp"
	mv ".tekton/$1.yaml.tmp" ".tekton/$1.yaml"
}

mkdir -p .tekton
# A newer push to a pull request cancels its older run; every master run
# finishes.
render pull-request pull_request 'event == "pull_request" && target_branch == "master"' true
render push push 'event == "push" && target_branch == "master"' false
